const kind = msg.payload?.kind;
const testMode = msg._location_test === true || msg.payload?.test_mode === true;
const domain = kind === "people_context" ? "people" : kind === "vehicle_primary_context" ? "vehicle_primary" : null;
msg.context_snapshot_valid = Boolean(domain && msg.payload?.context && typeof msg.payload.context === "object");
if (!msg.context_snapshot_valid) return msg;
const key = `${domain}_context_v1${testMode ? "__test" : ""}`;
const previous = flow.get(key);
const incomingAt = Number(msg.payload.updated_at ?? msg.payload.context.updated_at ?? 0);
const previousAt = Number(previous?.updated_at ?? 0);
const now = Number(msg.monitor_now ?? Date.now());
msg._location_test = testMode;
msg._location_test_case = msg._location_test_case ?? msg.payload?.test_case ?? null;
msg.context_domain = domain;
msg.context_cache_key = key;
msg.context_previous = previous;
msg.context_incoming_at = incomingAt;
msg.context_previous_at = previousAt;
msg.context_now = now;
msg.context_is_future = incomingAt > now + msg.policy.future_tolerance_s * 1000;
msg.context_is_out_of_order = Boolean(previous && incomingAt && previousAt && incomingAt < previousAt);
msg.context_missing_timestamp = !incomingAt;
msg.context_is_newer = !previous || Boolean(incomingAt && (!previousAt || incomingAt > previousAt));
msg.context_same_changed = incomingAt === previousAt && JSON.stringify(previous) !== JSON.stringify(msg.payload.context);
return msg;
