#!/usr/bin/env node
// Builds the English copies of the Portuguese Home Assistant dashboards.
//
// The Portuguese YAML in homeassistant/dashboards/ is the source of truth.
// Only text fields are translated (TEXT_KEYS); entities, actions, paths,
// conditions and template logic are copied verbatim, and --check proves it:
//   node scripts/dashboard-i18n.mjs          # write homeassistant/dashboards/en/*
//   node scripts/dashboard-i18n.mjs --check  # fail if stale, untranslated or diverging
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "nodered", "package.json"));
const yaml = require("js-yaml");

const DASHBOARDS = path.join(root, "homeassistant", "dashboards");
const CATALOG = path.join(DASHBOARDS, "i18n", "en.json");
const TEXT_KEYS = new Set(["title", "heading", "name", "label", "text", "content"]);
const HEADER = "# GENERATED by scripts/dashboard-i18n.mjs from ../{source} and i18n/en.json.\n# Edit the Portuguese source or the catalog, then run the script; do not edit this file.\n";
const PORTUGUESE = /[áàâãéêíóôõúç]|\b(?:de|da|dos|das|em|na|para|com|sem|ou|ainda|quando|aguardando|dados)\b/i;

const catalog = JSON.parse(fs.readFileSync(CATALOG, "utf8"));
const keep = new Set(catalog.keep);
const exact = new Map(Object.entries(catalog.exact));
const phrases = catalog.phrases;
const navigation = catalog.navigation || {};

// Links inside an English dashboard lead to the English copy of the target.
function localizePath(value) {
  for (const [from, to] of Object.entries(navigation)) {
    if (value === from || value.startsWith(`${from}/`)) return to + value.slice(from.length);
  }
  return value;
}

// Template fragments that decide behavior must be identical in both languages.
function logicSignature(text) {
  const patterns = [
    /\b(?:states|state_attr|is_state|is_number|as_timestamp|as_datetime)\([^)]*\)/g,
    /(?:==|!=)\s*(?:'[^']*'|"[^"]*"|[\w.]+)/g,
    /\bin \[(?:\s*'[^']*'\s*,?)+\]/g,
    /\.get\('[^']*'/g,
    /\{%\s*(?:if|elif|for|set [a-z_]+ =)[^%]*?(?=\s|%)/g,
  ];
  return patterns.flatMap((pattern) => text.match(pattern) || []);
}

// Visible prose: drop {% … %} blocks and keep only quoted literals from {{ … }}.
function visibleProse(text) {
  const literals = [];
  const outside = text
    .replace(/\{%[\s\S]*?%\}/g, " ")
    .replace(/\{\{([\s\S]*?)\}\}/g, (_m, inner) => {
      for (const literal of inner.match(/'[^']*'/g) || []) literals.push(literal.slice(1, -1));
      return " ";
    })
    .replace(/`[^`]*`/g, " ");
  return [outside, ...literals.filter((literal) => /\s/.test(literal))].join("\n");
}

function translateString(value, key, where, problems) {
  if (keep.has(value) || !/[A-Za-zÀ-ú]/.test(value)) return value;
  if (exact.has(value)) return exact.get(value);
  if (key !== "content") {
    problems.push(`${where}: no catalog entry for ${JSON.stringify(value)}`);
    return value;
  }
  let out = value;
  for (const [pt, en] of phrases) out = out.split(pt).join(en);
  const prose = visibleProse(out);
  if (PORTUGUESE.test(prose)) {
    const line = prose.split("\n").find((candidate) => PORTUGUESE.test(candidate)) || "";
    problems.push(`${where}: Portuguese left in content: ${JSON.stringify(line.trim().slice(0, 140))}`);
  }
  const before = logicSignature(value).join("\n");
  const after = logicSignature(out).join("\n");
  if (before !== after) problems.push(`${where}: translation changed template logic`);
  return out;
}

function walk(node, where, problems, parentKey) {
  if (Array.isArray(node)) return node.map((item, index) => walk(item, `${where}[${index}]`, problems, parentKey));
  if (node && typeof node === "object") {
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      if (typeof value === "string" && TEXT_KEYS.has(key)) out[key] = translateString(value, key, `${where}/${key}`, problems);
      else if (key === "navigation_path" && typeof value === "string") out[key] = localizePath(value);
      else out[key] = walk(value, `${where}/${key}`, problems, key);
    }
    return out;
  }
  return node;
}

// Everything except text fields must match the Portuguese source exactly.
function structure(node) {
  if (Array.isArray(node)) return node.map(structure);
  if (node && typeof node === "object") {
    return Object.fromEntries(Object.entries(node).map(([key, value]) => [
      key, TEXT_KEYS.has(key) && typeof value === "string" ? (key === "content" ? logicSignature(value) : "<text>")
        : key === "navigation_path" && typeof value === "string" ? localizePath(value) : structure(value),
    ]));
  }
  return node;
}

export function build() {
  const problems = [];
  const files = [];
  for (const [source, target] of Object.entries(catalog.outputs)) {
    const parsed = yaml.load(fs.readFileSync(path.join(DASHBOARDS, source), "utf8"));
    const translated = walk(parsed, source, problems);
    if (JSON.stringify(structure(parsed)) !== JSON.stringify(structure(translated))) {
      problems.push(`${source}: English copy diverges from the source structure`);
    }
    const body = yaml.dump(translated, { lineWidth: -1, noRefs: true, quotingType: '"' });
    files.push({ target: path.join(DASHBOARDS, target), text: HEADER.replace("{source}", source) + body });
  }
  return { files, problems };
}

function main() {
  const check = process.argv.includes("--check");
  const { files, problems } = build();
  for (const file of files) {
    const current = fs.existsSync(file.target) ? fs.readFileSync(file.target, "utf8") : null;
    if (check && current !== file.text) problems.push(`${path.relative(root, file.target)} is stale; run node scripts/dashboard-i18n.mjs`);
    if (!check && current !== file.text) {
      fs.mkdirSync(path.dirname(file.target), { recursive: true });
      fs.writeFileSync(file.target, file.text);
    }
  }
  if (problems.length) {
    for (const problem of problems) console.error(problem);
    process.exit(1);
  }
  console.log(`Dashboard i18n ${check ? "check passed" : "written"}: ${files.length} English dashboard(s).`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
